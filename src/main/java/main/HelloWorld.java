package main;

/**
 * Demonstrates the basic structure of a Java program by printing "Hello World" to the console.
 * Shows variable declaration, initialization, and output using {@code System.out.print}.
 *
 * @author Daniel Appenmaier
 * @version 1.0
 */
public class HelloWorld {

   public static void main(String[] args) {
      String text; // Declaration
      text = "Hello World"; // Initialization

      /* Output */
      System.out.print(text);
   }

}
